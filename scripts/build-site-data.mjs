import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const siteData = resolve(root, "site/src/data");

function readJsonl(text) {
  return text.split(/\r?\n/).filter(Boolean).map((line, index) => {
    try {
      return JSON.parse(line);
    } catch (error) {
      throw new Error(`Invalid JSONL at line ${index + 1}: ${error.message}`);
    }
  });
}

function decodeEntities(text) {
  return String(text ?? "")
    .replaceAll("&#39;", "'")
    .replaceAll("&quot;", "\"")
    .replaceAll("&amp;", "&")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">");
}

function displayTitle(title) {
  return decodeEntities(title)
    .replaceAll("$\\tau_0$", "τ₀")
    .replaceAll("$\\pi_0$", "π₀")
    .replaceAll("$\\pi_{0.5}$", "π₀.₅")
    .replaceAll("$\\pi_{0.7}$", "π₀.₇")
    .replaceAll("$τ_0$", "τ₀")
    .replaceAll("$π_0$", "π₀")
    .replaceAll("$π_{0.5}$", "π₀.₅")
    .replaceAll("$π_{0.7}$", "π₀.₇");
}

function nickname(title, arxivId) {
  const cleaned = decodeEntities(title).replaceAll("$", "");
  const match = cleaned.match(/^(.{2,42}?)\s*[:：]\s+\S/);
  if (match) return match[1].trim();
  return arxivId;
}

function authorsFrom(short) {
  if (!short || typeof short !== "string") return [];
  return short.split(",").map((part) => part.trim()).filter(Boolean);
}

function writeModule(name, exports) {
  const body = Object.entries(exports).map(([key, value]) => (
    `export const ${key} = ${JSON.stringify(value, null, 2)};\n`
  )).join("\n");
  return `// Generated by scripts/build-site-data.mjs from verified jsonl. Do not edit by hand.\n${body}`;
}

export async function buildSiteData() {
  const [mergedText, detailedText, ossText] = await Promise.all([
    readFile(resolve(root, "papers_merged.jsonl"), "utf8"),
    readFile(resolve(root, "papers_detailed.jsonl"), "utf8"),
    readFile(resolve(root, "oss_repos.jsonl"), "utf8"),
  ]);

  const merged = readJsonl(mergedText);
  const detailed = readJsonl(detailedText);
  const ossRows = readJsonl(ossText);
  const detailedById = new Map(detailed.map((row) => [row.arxiv_id, row]));

  if (merged.length === 0) throw new Error("papers_merged.jsonl is empty");
  if (merged.some((row) => !row.verified)) throw new Error("Refusing unverified paper rows");
  if (ossRows.some((row) => !row.verified)) throw new Error("Refusing unverified OSS rows");

  const papers = merged.map((row) => {
    const extra = detailedById.get(row.arxiv_id) ?? {};
    if (!row.arxiv_id || !row.title || !row.url) {
      throw new Error(`Incomplete paper row: ${row.arxiv_id ?? row.title}`);
    }
    if (!row.url.startsWith("https://arxiv.org/")) {
      throw new Error(`Unexpected paper URL for ${row.arxiv_id}`);
    }
    return {
      id: row.arxiv_id,
      nickname: nickname(displayTitle(row.title), row.arxiv_id),
      title: displayTitle(row.title),
      authors: authorsFrom(row.authors_short ?? extra.authors_short),
      year: row.year,
      published: `${row.year}-01-01`,
      tags: row.tags ?? [],
      sources: row.sources ?? [],
      venue: row.venue || "",
      abstract: decodeEntities(row.abstract_en ?? extra.abstract_en ?? ""),
      abstractZh: decodeEntities(row.abstract_zh ?? extra.abstract_zh ?? ""),
      highlightsZh: extra.highlights_zh ?? row.highlights_zh ?? [],
      abstractSource: row.abstract_source ?? extra.abstract_source ?? "",
      arxiv: row.url,
      pdf: `https://arxiv.org/pdf/${row.arxiv_id}`,
    };
  });

  const seen = new Set();
  for (const paper of papers) {
    if (seen.has(paper.id)) throw new Error(`Duplicate arXiv ID: ${paper.id}`);
    seen.add(paper.id);
  }

  const oss = ossRows.map((row) => {
    if (!row.name || !row.org || !row.url) throw new Error(`Incomplete OSS row: ${row.name}`);
    if (!row.url.startsWith("https://github.com/")) throw new Error(`Unexpected OSS URL: ${row.url}`);
    return {
      id: `${row.org}/${row.name}`,
      name: row.name,
      org: row.org,
      title: `${row.org}/${row.name}`,
      nickname: row.name,
      url: row.url,
      license: row.license,
      stars: Number(row.stars) || 0,
      family: row.family,
      modality: row.primary_modality,
      lastActivity: row.last_activity_hint,
      relatedPapers: row.related_papers ?? [],
      notes: row.notes,
    };
  });

  const paperById = new Map(papers.map((paper) => [paper.id, paper]));
  const extraPaperIds = new Set();
  const compositionEdges = [];
  for (const repo of oss) {
    for (const arxivId of repo.relatedPapers) {
      extraPaperIds.add(arxivId);
      compositionEdges.push({
        source: `oss:${repo.id}`,
        target: `paper:${arxivId}`,
        verifiedBy: "oss-related-papers",
      });
    }
  }

  const compositionNodes = [
    ...oss.map((repo) => ({
      id: `oss:${repo.id}`,
      kind: "oss",
      nickname: repo.name,
      title: repo.title,
      authors: [repo.org],
      year: 0,
      published: "2026-09-12",
      citations: repo.stars,
      arxiv: repo.url,
      pdf: repo.url,
    })),
    ...[...extraPaperIds].map((arxivId) => {
      const paper = paperById.get(arxivId);
      return {
        id: `paper:${arxivId}`,
        kind: "paper",
        nickname: paper?.nickname ?? arxivId,
        title: paper?.title ?? `arXiv:${arxivId}`,
        authors: paper?.authors ?? [],
        year: paper?.year ?? 0,
        published: paper?.published ?? "2018-01-01",
        citations: 1,
        arxiv: paper?.arxiv ?? `https://arxiv.org/abs/${arxivId}`,
        pdf: paper?.pdf ?? `https://arxiv.org/pdf/${arxivId}`,
      };
    }),
  ];

  const compositionGraphMeta = {
    snapshot: "2026-09-12",
    scope: "Verified OSS related_papers only; not a citation graph",
    sourceName: "oss_repos.jsonl",
    sourceUrl: "https://github.com/topsun-bot/wm-vla-vln-vlm-survey/blob/main/oss_repos.jsonl",
    edges: compositionEdges.length,
  };

  const counts = {
    papers: papers.length,
    oss: oss.length,
    abstracts: papers.filter((paper) => paper.abstract).length,
    tags: Object.fromEntries(
      [...new Set(papers.flatMap((paper) => paper.tags))]
        .sort()
        .map((tag) => [tag, papers.filter((paper) => paper.tags.includes(tag)).length]),
    ),
    years: Object.fromEntries(
      [...new Set(papers.map((paper) => paper.year))]
        .sort((a, b) => b - a)
        .map((year) => [year, papers.filter((paper) => paper.year === year).length]),
    ),
    families: Object.fromEntries(
      [...new Set(oss.map((repo) => repo.family))]
        .sort()
        .map((family) => [family, oss.filter((repo) => repo.family === family).length]),
    ),
    compositionEdges: compositionEdges.length,
  };

  await mkdir(siteData, { recursive: true });
  await Promise.all([
    writeFile(resolve(siteData, "papers.js"), writeModule("papers", { papers, paperCounts: counts })),
    writeFile(resolve(siteData, "oss.js"), writeModule("oss", { oss })),
    writeFile(
      resolve(siteData, "compositionGraph.js"),
      writeModule("compositionGraph", {
        compositionNodes,
        compositionEdges,
        compositionGraphMeta,
      }),
    ),
  ]);

  return counts;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const counts = await buildSiteData();
  console.log(
    `Wrote site data: ${counts.papers} papers, ${counts.oss} OSS, ${counts.compositionEdges} composition edges.`,
  );
}
